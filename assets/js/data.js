  /* --- deterministic PRNG (mulberry32) ----------------------------------- */
  function rng(seed) {
    let t = seed >>> 0;
    return function () {
      t += 0x6D2B79F5;
      let r = Math.imul(t ^ (t >>> 15), 1 | t);
      r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
      return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
    };
  }
  function gauss(rand) {
    let u = 0, v = 0;
    while (u === 0) u = rand();
    while (v === 0) v = rand();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  }
  const seedOf = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };

  /* --- SECTION 4 : Shot DNA ---------------------------------------------- */
  function buildShotDNA(code, p) {
    const rand = rng(seedOf(code + "shot"));

    // 4-a Driver carry distribution (histogram, 5m buckets)
    const carries = [];
    for (let i = 0; i < 120; i++) carries.push(p.carry + gauss(rand) * p.carrySd);
    const lo = 205, hi = 275, step = 5;
    const driver = [];
    for (let b = lo; b < hi; b += step) {
      driver.push({ from: b, to: b + step, label: b + "", count: carries.filter((c) => c >= b && c < b + step).length });
    }
    const sorted = carries.slice().sort((a, b) => a - b);
    const q = (t) => sorted[Math.floor(sorted.length * t)];

    // 4-b Approach proximity distribution by distance band
    const bands = [
      { band: "~80m", n: 26 }, { band: "80-110m", n: 34 },
      { band: "110-140m", n: 31 }, { band: "140m+", n: 22 }
    ];
    const approach = bands.map((b, i) => {
      const base = p.prox + i * 1.9;
      const vals = Array.from({ length: b.n }, () => Math.max(0.6, base + gauss(rand) * (1.5 + i * 0.4)));
      const avg = vals.reduce((a, c) => a + c, 0) / vals.length;
      return {
        band: b.band,
        shots: b.n,
        prox: +avg.toFixed(1),
        inside3: Math.round((vals.filter((v) => v <= 3).length / vals.length) * 100),
        gir: Math.max(30, Math.min(95, Math.round(p.gir - i * 7 + (rand() * 6 - 3))))
      };
    });

    // 4-c Landing distribution — tee-shot landing points vs fairway centre
    const landing = [];
    for (let i = 0; i < 54; i++) {
      const x = gauss(rand) * p.disp;
      const y = p.carry + gauss(rand) * p.carrySd;
      const ax = Math.abs(x);
      const result = ax <= 13 ? "FAIRWAY" : ax <= 22 ? (rand() > 0.72 ? "BUNKER" : "ROUGH") : "ROUGH";
      landing.push({ x: +x.toFixed(1), y: +y.toFixed(1), result: result, hole: 1 + Math.floor(rand() * 18) });
    }

    return {
      driver: {
        bins: driver, binStep: step,
        median: +q(0.5).toFixed(1), p10: +q(0.1).toFixed(1), p90: +q(0.9).toFixed(1),
        shots: carries.length
      },
      approach: approach,
      landing: {
        points: landing,
        fairwayWidth: 26,
        fairwayHit: Math.round((landing.filter((l) => l.result === "FAIRWAY").length / landing.length) * 100),
        missBias: landing.reduce((a, c) => a + c.x, 0) / landing.length
      }
    };
  }

  /* --- SECTION 7 : Hole Library ------------------------------------------ */
  function buildHoleLibrary(code, p) {
    const rand = rng(seedOf(code + "hole"));
    const lies = ["FAIRWAY", "ROUGH", "BUNKER", "TEE"];
    const rows = [];
    for (let i = 0; i < 12; i++) {
      const round = 1 + Math.floor(i / 3);
      const hole = 1 + Math.floor(rand() * 18);
      const par = [3, 4, 4, 4, 5][Math.floor(rand() * 5)];
      // hole length (m) → 티샷 캐리 후 남은 거리
      const holeLen = par === 3 ? Math.round(135 + rand() * 45)
        : par === 4 ? Math.round(320 + rand() * 70)
          : Math.round(450 + rand() * 50);
      const carry = par === 3 ? holeLen - Math.round(rand() * 8) : Math.round(p.carry + gauss(rand) * p.carrySd);
      const left = par === 3 ? Math.round(1 + rand() * 11) : Math.round(holeLen - carry);
      const lie = par === 3 ? "TEE" : lies[Math.floor(rand() * 3)];
      const s = rand();
      const qa = s > 0.62 ? "GOOD" : s > 0.24 ? "OK" : "MISS";
      rows.push({
        id: code + "-r" + round + "-h" + hole + "-" + i,
        round: round, hole: hole, par: par,
        carry: carry, left: Math.max(2, left), lie: lie, qa: qa,
        note: qa === "GOOD"
          ? "페어웨이 중앙, 다음 샷 각도 확보. 핀까지 " + Math.max(2, left) + "m."
          : qa === "OK"
            ? "라이는 살았지만 핀 공략 각도가 제한됨. 레이업 선택 가능."
            : "미스 방향 " + (rand() > 0.5 ? "좌측" : "우측") + ", 리커버리 샷 필요."
      });
    }
    return rows.sort((a, b) => a.round - b.round || a.hole - b.hole);
  }

